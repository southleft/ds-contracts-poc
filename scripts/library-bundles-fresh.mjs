/**
 * LIBRARY PASTE BUNDLES — the committed `<lib>.bundle.json` vs a rebuild.
 *
 *   npm run bundle:fresh
 *
 * WHY THIS EXISTS. `examples/<lib>/figma/<lib>.bundle.json` is the ONE JSON a
 * team pastes into Figma — contracts + the whole token set + icons in a single
 * artifact. It is also, and this is the part that bit:
 * `extract/figma/census/corpus.ts:290` reads it as "the SAME token layer the
 * canvas is minted from", so the CENSUS CODE HALF renders every example-library
 * row through this file and nothing else.
 *
 * MEASURED HOLE, found by walking into it. A round that re-derived two contracts
 * re-emitted the scripts, the DTCG trees, the genesis batches and the compile
 * receipts — every remedy the repo documents — and `figma:fresh` reported 9/9
 * byte-fresh, `generated:fresh` 3/3, `conformance` green, `maintain` green. The
 * bundles were stale the whole time, and the only reason anyone found out was
 * that the census render then refused BY NAME:
 *
 *   ✘ shadcn/shadcn.avatar — UNAVAILABLE (engine compile refused —
 *       Cannot resolve token "imported.avatar.label.height.default")
 *
 * A refusal is the lucky case. Had the round only CHANGED a token's value
 * rather than added one, the census would have rendered the old value with
 * every gate green — which is the "the engine moved, the artifacts did not"
 * class, on the one artifact a designer actually pastes.
 *
 * Only two bundles were gated before this file: tailwind's, by
 * scripts/flowbite-bundle-fresh-check.ts (hop-2 pin, by name), and the
 * first-party set, by core/first-party-bundle-check.ts. The other eight
 * shipped ungated.
 *
 * THE RECIPE is conventional, not configured — that is deliberate, so a new
 * library cannot be added with a hand-written arg list nobody re-runs:
 *
 *   figma bundle examples/<lib>/contracts
 *     --tokens  examples/<lib>/tokens/<lib>.dtcg.json[,<lib>-minted.dtcg.json]
 *     --modes   examples/<lib>/tokens/modes/<lib>.{light,dark}.dtcg.json   (when present)
 *     --name    <the committed tokenSet.name>
 *     --icons   examples/<lib>/assets/icons                                 (when present)
 *
 * `--modes` is load-bearing and its absence is SILENT: omit it and the rebuild
 * drops tokenSet.modes entirely — a 3,333-line deletion across two bundles in
 * the round that wrote this file, which every other gate accepted. The
 * comparison below is byte-for-byte precisely so that cannot pass.
 *
 * NAMED HOLE — polaris. Its bundle cannot be rebuilt by this recipe: the CLI
 * refuses 8 of its 12 contracts against the conventional token set ("8 of 12
 * contract(s) do not compile against this token set; the plugin would refuse
 * each of them on paste, so nothing was written"). Polaris is generated by
 * `examples/polaris/generate.ts`, whose `--check` mode holds its scripts still
 * for figma:fresh — but `grep -n bundle examples/polaris/generate.ts` returns
 * NOTHING, so polaris.bundle.json is held by no gate at all. It is reported
 * here as an UNGATED hole rather than silently skipped, and closing it means
 * teaching generate.ts to emit and check its own bundle.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, readdirSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const ROOT = process.cwd();
const TSX = path.join(ROOT, 'node_modules', '.bin', 'tsx');
const CLI = 'packages/cli/src/cli.ts';

/** Libraries whose bundle this recipe provably cannot rebuild, with the
 *  MEASURED refusal. An entry here is a hole that is named, not a skip. */
const UNGATED = {
  polaris:
    'the conventional recipe refuses 8 of 12 contracts against examples/polaris/tokens ("do not compile against this token set; the plugin would refuse each of them on paste"). polaris is emitted by examples/polaris/generate.ts, which holds its *.figma.js still for figma:fresh but never touches polaris.bundle.json — grep -n bundle examples/polaris/generate.ts returns nothing. Remedy: teach generate.ts to emit and --check its own bundle.',
};

const libs = readdirSync(path.join(ROOT, 'examples'), { withFileTypes: true })
  .filter((e) => e.isDirectory())
  .map((e) => e.name)
  .filter((l) => existsSync(path.join(ROOT, 'examples', l, 'figma', `${l}.bundle.json`)))
  .sort();

const failures = [];
const rows = [];

for (const lib of libs) {
  const committedPath = path.join(ROOT, 'examples', lib, 'figma', `${lib}.bundle.json`);
  if (UNGATED[lib]) {
    rows.push([lib, 'UNGATED', UNGATED[lib].slice(0, 110) + '…']);
    continue;
  }
  const committedText = readFileSync(committedPath, 'utf8');
  let committed;
  try {
    committed = JSON.parse(committedText);
  } catch {
    failures.push(`${lib}: committed ${lib}.bundle.json is not valid JSON`);
    rows.push([lib, 'UNPARSEABLE', '']);
    continue;
  }
  const name = committed?.tokenSet?.name;
  if (typeof name !== 'string' || name.length === 0) {
    failures.push(`${lib}: committed bundle has no tokenSet.name — the rebuild cannot name its collection`);
    rows.push([lib, 'NO-NAME', '']);
    continue;
  }

  const tokDir = path.join(ROOT, 'examples', lib, 'tokens');
  const tokens = [`${lib}.dtcg.json`, `${lib}-minted.dtcg.json`]
    .filter((f) => existsSync(path.join(tokDir, f)))
    .map((f) => `examples/${lib}/tokens/${f}`);
  if (tokens.length === 0) {
    failures.push(`${lib}: no examples/${lib}/tokens/${lib}.dtcg.json — the conventional recipe has nothing to bundle`);
    rows.push([lib, 'NO-TOKENS', '']);
    continue;
  }
  // The modes pair, when the library has one. Its absence from the command is
  // SILENT — the bundle simply loses tokenSet.modes — so it is derived from
  // the files on disk rather than trusted to a list.
  const modes = ['light', 'dark']
    .filter((m) => existsSync(path.join(tokDir, 'modes', `${lib}.${m}.dtcg.json`)))
    .map((m) => `examples/${lib}/tokens/modes/${lib}.${m}.dtcg.json`);
  const hasModes = Boolean(committed?.tokenSet?.modes && Object.keys(committed.tokenSet.modes).length > 0);
  if (hasModes && modes.length === 0) {
    failures.push(
      `${lib}: the committed bundle carries tokenSet.modes (${Object.keys(committed.tokenSet.modes).join('/')}) but examples/${lib}/tokens/modes/ has no ${lib}.{light,dark}.dtcg.json to rebuild them from — the modes in the shipped paste artifact come from a source this gate cannot see`,
    );
    rows.push([lib, 'MODES-UNSOURCED', '']);
    continue;
  }
  const iconsDir = path.join(ROOT, 'examples', lib, 'assets', 'icons');
  const out = path.join(mkdtempSync(path.join(os.tmpdir(), `bundle-fresh-${lib}-`)), 'b.json');
  const args = [
    CLI,
    'figma',
    'bundle',
    `examples/${lib}/contracts`,
    '--tokens',
    tokens.join(','),
    ...(modes.length > 0 ? ['--modes', modes.join(',')] : []),
    '--name',
    name,
    ...(existsSync(iconsDir) ? ['--icons', `examples/${lib}/assets/icons`] : []),
    '--out',
    out,
  ];

  try {
    execFileSync(TSX, args, { cwd: ROOT, stdio: 'pipe' });
  } catch (err) {
    // An emit REFUSAL is a freshness verdict, not an instrument crash — the
    // same call figma:fresh makes on its own emit path.
    failures.push(
      `${lib}: fresh bundle REFUSED — the committed paste artifact cannot be freshness-checked until the bundle emits:\n${String(err.stderr ?? err.stdout ?? err.message).slice(0, 900)}`,
    );
    rows.push([lib, 'EMIT-REFUSED', '']);
    continue;
  }

  const fresh = readFileSync(out, 'utf8');
  if (fresh !== committedText) {
    failures.push(
      `${lib}: committed ${lib}.bundle.json is STALE vs a fresh build — re-run\n` +
        `    npx tsx ${args.slice(0, -2).join(' ')} --out examples/${lib}/figma/${lib}.bundle.json\n` +
        `  and commit it. This is the ONE JSON a team pastes into Figma AND the token layer extract/figma/census/corpus.ts renders every ${lib} census code half through.`,
    );
    rows.push([lib, 'STALE', `${modes.length > 0 ? 'base+minted+modes' : 'base+minted'}`]);
    continue;
  }
  rows.push([lib, 'fresh', `${committed.contracts?.length ?? '?'} contracts, ${modes.length > 0 ? 'base+minted+modes' : 'base+minted'}`]);
}

console.log('');
for (const [lib, status, note] of rows) console.log(`  ${lib.padEnd(10)} ${status.padEnd(15)} ${note}`);
console.log('');

if (failures.length > 0) {
  console.error(`✖ library-bundles-fresh: ${failures.length} failure(s)\n`);
  for (const f of failures) console.error(`  ${f}\n`);
  process.exit(1);
}

const gated = rows.filter((r) => r[1] === 'fresh').length;
const holes = rows.filter((r) => r[1] === 'UNGATED');
console.log(
  `✔ library-bundles-fresh: ${gated}/${rows.length} committed paste bundles byte-identical to a rebuild` +
    (holes.length > 0 ? ` (${holes.length} named hole: ${holes.map((h) => h[0]).join(', ')} — see the header)` : ' (0 named holes)'),
);
