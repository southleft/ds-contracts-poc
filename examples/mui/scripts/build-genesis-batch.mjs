/**
 * MUI genesis — ONE paste-able script for the whole first library.
 *   `node examples/mui/scripts/build-genesis-batch.mjs`
 *
 * Concatenates 00-tokens + the 11 component sync scripts, each wrapped in its
 * own async block scope (per-script consts stay isolated — the same isolation
 * the plugin's per-paste runScript gives). Paste the output ONCE into the
 * plugin's "Paste a script" tab on a blank file: tokens upsert first
 * (Light/Dark, Figma-native aliases), then every component. MOLECULE round:
 * Menu and Tooltip are STANDALONE (no variant axes) — they build a COMPONENT,
 * not a COMPONENT_SET; the mock proof counts both kinds by name.
 *
 * PROVEN before writing: the exact concatenated output is executed against
 * the mocked `figma` global (scripts/plugin-engine-mock-figma.mjs) and must
 * build every component set without throwing — the builder REFUSES to write
 * a batch it cannot run. Deterministic end to end — emitted by the CLI from
 * the contracts, executed verbatim by the plugin, no AI in the conversion.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
import { createFigmaMock } from '../../../scripts/plugin-engine-mock-figma.mjs';

const EX = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const F = (f) => readFileSync(path.join(EX, 'figma', f), 'utf8');

const ORDER = [
  '00-tokens.figma.js',
  'button.figma.js', 'card.figma.js', 'chip.figma.js', 'slider.figma.js', 'switch.figma.js',
  'tabs.figma.js', 'accordion.figma.js', 'autocomplete.figma.js', 'dialog.figma.js',
  'menu.figma.js', 'tooltip.figma.js',
];
// standalone (no variant axes → COMPONENT, not COMPONENT_SET)
const STANDALONE = ['Menu', 'Tooltip'];

const blocks = ORDER.map((f) => `// ───── ${f} ─────
await (async () => {
${F(f)}
})();`).join('\n\n');

const expectedSets = ORDER.length - 1 - STANDALONE.length;
const out = `// MUI GENESIS — the first MUI (@mui/material@9.2.0 default theme) Figma library, one deterministic paste.
// GENERATED by examples/mui/scripts/build-genesis-batch.mjs — do not edit.
// Order: tokens (Light/Dark + Figma-native source aliases) → ${expectedSets} component sets + ${STANDALONE.length} standalone components.
${blocks}
figma.notify('MUI genesis complete: tokens + ${expectedSets} component sets + ${STANDALONE.length} standalone components.');
`;

// refuse-to-write proof: the EXACT output must run headlessly end to end
const mock = createFigmaMock();
const ctx = vm.createContext({ figma: mock.figma, console: { log() {}, warn() {}, error() {} } });
await vm.runInContext(`(async () => {\n${out}\n})()`, ctx, { timeout: 300_000 });
const sets = mock.root.findAll((n) => n.type === 'COMPONENT_SET');
const vars = await mock.figma.variables.getLocalVariablesAsync();
if (sets.length !== expectedSets) {
  console.error(`✘ genesis batch REFUSED: mock built ${sets.length}/${expectedSets} component sets (${sets.map((s) => s.name).join(', ')})`);
  process.exit(1);
}
const singles = mock.root.findAll((n) => n.type === 'COMPONENT' && STANDALONE.includes(n.name));
if (singles.length !== STANDALONE.length) {
  console.error(`✘ genesis batch REFUSED: mock built ${singles.length}/${STANDALONE.length} standalone components (want ${STANDALONE.join(', ')}; got ${singles.map((s) => s.name).join(', ') || 'none'})`);
  process.exit(1);
}

writeFileSync(path.join(EX, 'figma', 'GENESIS-BATCH.figma.js'), out);
console.log(`✔ GENESIS-BATCH.figma.js: ${ORDER.length} blocks, ${out.length} bytes — mock-proven (${sets.length} sets: ${sets.map((s) => `${s.name}(${s.children.length})`).join(', ')}; standalone: ${singles.map((s) => s.name).join(', ')}; ${vars.length} variables)`);
