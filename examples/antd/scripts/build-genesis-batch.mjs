/**
 * Ant Design genesis — ONE paste-able script for the whole library.
 *   `node examples/antd/scripts/build-genesis-batch.mjs`
 *
 * Concatenates 00-tokens + the component sync scripts, each wrapped in its own
 * async block scope (per-script consts stay isolated — the same isolation the
 * plugin's per-paste runScript gives). Paste the output ONCE into the plugin's
 * "Paste a script" tab on a blank file: tokens upsert first ("Ant Design"
 * collection, Light/Dark = antd's own getDesignToken() / darkAlgorithm — theme
 * objects, not a CSS scope; cssinjs ships no stylesheet), then every component set.
 *
 * PROVEN before writing: the exact concatenated output is executed against the
 * mocked `figma` global (scripts/plugin-engine-mock-figma.mjs) and must build
 * every component set without throwing — the builder REFUSES to write a batch
 * it cannot run. Deterministic end to end.
 *
 * The ORDER is read from the emitted directory, not hardcoded: a component
 * that stops emitting would otherwise vanish from the batch in silence.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
import { createFigmaMock } from '../../../scripts/plugin-engine-mock-figma.mjs';

const EX = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const FIGMA_DIR = path.join(EX, 'figma');
const F = (f) => readFileSync(path.join(FIGMA_DIR, f), 'utf8');

const componentScripts = readdirSync(FIGMA_DIR)
  .filter((f) => f.endsWith('.figma.js') && f !== '00-tokens.figma.js' && f !== 'GENESIS-BATCH.figma.js')
  .sort();
const ORDER = ['00-tokens.figma.js', ...componentScripts];

const blocks = ORDER.map((f) => `// ───── ${f} ─────
await (async () => {
${F(f)}
})();`).join('\n\n');

const out = `// ANT DESIGN GENESIS — the antd 5.29.3 (@ant-design/cssinjs, cssVar mode) Figma library, one deterministic paste.
// GENERATED by examples/antd/scripts/build-genesis-batch.mjs — do not edit.
// Order: tokens (Light/Dark from getDesignToken() + darkAlgorithm, Figma-native source aliases) → ${componentScripts.length} component sets.
${blocks}
figma.notify('Ant Design genesis complete: tokens + ${componentScripts.length} component sets.');
`;

// refuse-to-write proof: the EXACT output must run headlessly end to end
const mock = createFigmaMock();
const ctx = vm.createContext({ figma: mock.figma, console: { log() {}, warn() {}, error() {} } });
await vm.runInContext(`(async () => {\n${out}\n})()`, ctx, { timeout: 300_000 });
// A component with no enum axes builds as a STANDALONE COMPONENT, not a set —
// both shapes count as "built".
const sets = mock.root.findAll((n) => n.type === 'COMPONENT_SET');
const standalone = mock.root.findAll((n) => n.type === 'COMPONENT' && n.parent?.type !== 'COMPONENT_SET');
const built = sets.length + standalone.length;
const vars = await mock.figma.variables.getLocalVariablesAsync();
if (built !== componentScripts.length) {
  console.error(`✘ genesis batch REFUSED: mock built ${built}/${componentScripts.length} components (sets: ${sets.map((s) => s.name).join(', ')}; standalone: ${standalone.map((s) => s.name).join(', ')})`);
  process.exit(1);
}

writeFileSync(path.join(FIGMA_DIR, 'GENESIS-BATCH.figma.js'), out);
console.log(
  `✔ GENESIS-BATCH.figma.js: ${ORDER.length} blocks, ${out.length} bytes — mock-proven (${sets.length} sets: ${sets.map((s) => `${s.name}(${s.children.length})`).join(', ')}` +
    (standalone.length ? `; standalone: ${standalone.map((s) => s.name).join(', ')}` : '') +
    `; ${vars.length} variables)`,
);
